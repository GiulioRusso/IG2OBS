"""
ig_obsidian_archive.py
-----------------------
Builds an Obsidian archive of your own Instagram posts from two official
exports, without connecting any app to the account:

  1) Instagram "Download your information" export (JSON, High quality)
     -> images + caption + timestamp
  2) Meta Business Suite content export (CSV or XLSX)
     -> per-post metrics

The two sources share no ID, so the join happens on the publish timestamp
with a configurable tolerance. Ambiguous cases are NOT guessed: they end up
in a review CSV.

All options live in config/config.yaml. To override it:

    python ig_obsidian_archive.py --config /path/to/config.yaml

Semantic tagging uses Ollama (local or cloud, free): needs a reachable
Ollama server (default http://localhost:11434, override with OLLAMA_HOST).
For cloud models (tag suffixed "-cloud"): `ollama signin`.
"""

