def fix_mojibake(s: str) -> str:
    """
    The Instagram export serializes UTF-8 strings as if they were latin-1:
    apostrophes and accents turn into garbage, emoji become mangled bytes.
    This turns them back. If the string is already correct, it's left as-is.
    """
    if not s:
        return s
    try:
        candidate = s.encode("latin-1").decode("utf-8")
    except (UnicodeEncodeError, UnicodeDecodeError):
        return s
    # If the round-trip produced replacement characters, keep the original:
    # it means it wasn't mojibake.
    if "�" in candidate:
        return s
    return candidate


def slugify(text: str, max_len: int = 60) -> str:
    text = unicodedata.normalize("NFKD", text)
    text = text.encode("ascii", "ignore").decode("ascii")
    text = re.sub(r"[^\w\s-]", "", text).strip().lower()
    text = re.sub(r"[\s_-]+", "-", text)
    return text[:max_len].strip("-") or "post"


def yaml_quote(value: Any) -> str:
    """Serializes a scalar value for the YAML frontmatter."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    s = str(value)
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def log(msg: str) -> None:
    print(msg, file=sys.stderr)


