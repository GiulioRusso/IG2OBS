def axis_names(taxonomy: dict[str, Any]) -> list[str]:
    """Axes are the keys that don't start with an underscore."""
    return [k for k in taxonomy if not k.startswith("_")]


def axis_values(spec: dict[str, Any]) -> list[str]:
    return spec.get("values") or spec.get("valori") or []


def axis_description(spec: dict[str, Any]) -> str:
    return spec.get("description") or spec.get("descrizione") or ""


DEFAULT_INSTRUCTIONS = [
    "You are an archivist cataloguing posts from a page about space exploration.",
    "For each caption, assign the correct values for every axis of the taxonomy below.",
    "",
    "RULES:",
    "- Use ONLY the listed values. Never invent new ones.",
    "- If an axis cannot be determined from the caption, return an empty list [].",
    "- Ignore hashtags: they carry no information.",
]


def build_tagging_prompt(taxonomy: dict[str, Any]) -> str:
    # Instructions live in the JSON so you can change them (and their
    # language) without touching the code.
    instructions = taxonomy.get("_instructions") or DEFAULT_INSTRUCTIONS
    if isinstance(instructions, str):
        instructions = instructions.splitlines()
    lines = list(instructions) + ["", "TAXONOMY:"]

    axes = axis_names(taxonomy)
    for axis in axes:
        spec = taxonomy[axis]
        card = "multiple values allowed" if spec.get("multi") else "at most one value"
        lines.append(f"- {axis} ({card}): {axis_description(spec)}")
        lines.append(f"  values: {', '.join(axis_values(spec))}")

    lines += [
        "",
        "Respond ONLY with a JSON array, one object per caption, in the same",
        "order received, in this format:",
        '[{"id": "<received id>", ' + ", ".join(f'"{a}": []' for a in axes) + "}]",
        "No text before or after. No markdown fences.",
    ]
    return "\n".join(lines)


def clean_caption(caption: str, max_chars: int = 1200) -> str:
    text = re.sub(r"#\S+", "", caption)
    text = re.sub(r"\n{3,}", "\n\n", text).strip()
    return text[:max_chars]


def ollama_chat(model: str, system: str, user: str) -> str:
    """Calls Ollama's /api/chat (local or cloud) and returns the response text."""
    body = json.dumps({
        "model": model,
        "stream": False,
        "messages": [
            {"role": "system", "content": system},
            {"role": "user", "content": user},
        ],
    }).encode("utf-8")
    headers = {"Content-Type": "application/json"}
    if OLLAMA_API_KEY:
        headers["Authorization"] = f"Bearer {OLLAMA_API_KEY}"
    req = urllib.request.Request(
        f"{OLLAMA_HOST}/api/chat", data=body, headers=headers, method="POST"
    )
    try:
        with urllib.request.urlopen(req, timeout=120) as resp:
            data = json.loads(resp.read().decode("utf-8"))
    except urllib.error.URLError as exc:
        raise SystemExit(
            f"[!] Can't reach Ollama at {OLLAMA_HOST} ({exc}).\n"
            "    Local: start the server with `ollama serve`.\n"
            "    Cloud: run `ollama signin` (tags with -cloud suffix), "
            "or set OLLAMA_HOST/OLLAMA_API_KEY for the direct cloud endpoint."
        )
    return data["message"]["content"]


def tag_posts(posts: list[Post], taxonomy: dict[str, Any], model: str,
              batch_size: int, cache_path: Path) -> None:
    cache: dict[str, dict[str, list[str]]] = {}
    if cache_path.exists():
        cache = json.loads(cache_path.read_text(encoding="utf-8"))

    axes = axis_names(taxonomy)
    valid = {a: set(axis_values(taxonomy[a])) for a in axes}
    system = build_tagging_prompt(taxonomy)

    todo = []
    for p in posts:
        digest = hashlib.sha1(clean_caption(p.caption).encode()).hexdigest()[:16]
        if digest in cache:
            p.tags = cache[digest]
        elif clean_caption(p.caption):
            todo.append((digest, p))

    if not todo:
        log("[i] All tags were already cached.")
        return

    log(f"[i] To tag: {len(todo)} post(s) in {(len(todo) + batch_size - 1)//batch_size} call(s).")

    for start in range(0, len(todo), batch_size):
        batch = todo[start:start + batch_size]
        payload = [
            {"id": digest, "caption": clean_caption(p.caption)}
            for digest, p in batch
        ]
        try:
            text = ollama_chat(model, system, json.dumps(payload, ensure_ascii=False))
            text = re.sub(r"^```(?:json)?|```$", "", text.strip(),
                          flags=re.MULTILINE).strip()
            parsed = json.loads(text)
        except SystemExit:
            raise
        except Exception as exc:  # noqa: BLE001
            log(f"[!] Batch {start//batch_size + 1} failed ({exc}). Skipping it.")
            continue

        by_id = {str(item.get("id")): item for item in parsed if isinstance(item, dict)}
        for digest, post in batch:
            item = by_id.get(digest)
            if not item:
                continue
            tags: dict[str, list[str]] = {}
            for axis in axes:
                raw = item.get(axis) or []
                if isinstance(raw, str):
                    raw = [raw]
                kept = [v for v in raw if v in valid[axis]]
                if not taxonomy[axis].get("multi"):
                    kept = kept[:1]
                tags[axis] = kept
            post.tags = tags
            cache[digest] = tags

        cache_path.write_text(json.dumps(cache, ensure_ascii=False, indent=1),
                              encoding="utf-8")
        log(f"    batch {start//batch_size + 1} ok")


