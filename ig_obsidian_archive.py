def prepare_export(path: Path, workdir: Path) -> Path:
    """Extracts it if it's a ZIP, otherwise returns the folder as-is."""
    if path.is_dir():
        return path
    if path.suffix.lower() != ".zip":
        raise SystemExit(f"[!] ig_export must be a .zip or a folder: {path}")
    dest = workdir / "ig_export"
    stamp = workdir / "ig_export.zip.mtime"
    current_mtime = path.stat().st_mtime
    if dest.exists():
        if stamp.exists() and stamp.read_text() == str(current_mtime):
            log(f"[i] Export already extracted in {dest}, reusing.")
            return dest
        shutil.rmtree(dest)
    log(f"[i] Extracting {path.name} ...")
    dest.mkdir(parents=True, exist_ok=True)
    failed = 0
    with zipfile.ZipFile(path) as zf:
        for inf in zf.infolist():
            # Undownloaded/placeholder entries: skip and move on. Notes are
            # still generated, just missing some media.
            try:
                zf.extract(inf, dest)
            except (OSError, zipfile.BadZipFile):
                failed += 1
    if failed:
        log(f"[!] {failed} file(s) not extracted (undownloaded placeholders?): "
            f"the corresponding notes will be missing media.")
    stamp.write_text(str(current_mtime))
    return dest


def find_posts_json(root: Path) -> Path:
    for rel in POSTS_JSON_CANDIDATES:
        p = root / rel
        if p.exists():
            return p
    # Fallback: look everywhere for a posts_*.json
    matches = sorted(root.rglob("posts_1.json")) or sorted(root.rglob("posts_*.json"))
    if matches:
        return matches[0]
    raise SystemExit(
        "[!] Can't find the posts JSON inside the export.\n"
        "    Make sure you picked the JSON format (not HTML) when downloading."
    )


def parse_ig_export(root: Path) -> list[Post]:
    posts_json = find_posts_json(root)
    log(f"[i] Reading {posts_json.relative_to(root)}")
    with open(posts_json, "r", encoding="utf-8") as f:
        raw = json.load(f)

    if isinstance(raw, dict):
        # Some export versions wrap the list in a key
        for key in ("posts", "media", "ig_posts"):
            if key in raw and isinstance(raw[key], list):
                raw = raw[key]
                break
        else:
            raise SystemExit("[!] Unrecognized posts JSON structure.")

    posts: list[Post] = []
    for entry in raw:
        media_items = entry.get("media") or []
        if not media_items:
            continue

        # Caption: at the post level for carousels, inside the first media
        # item for single posts.
        caption = entry.get("title") or ""
        if not caption and media_items:
            caption = media_items[0].get("title") or ""
        caption = fix_mojibake(caption)

        ts_raw = entry.get("creation_timestamp") or media_items[0].get("creation_timestamp")
        if not ts_raw:
            continue
        ts = datetime.fromtimestamp(int(ts_raw), tz=timezone.utc)

        paths = []
        for m in media_items:
            uri = m.get("uri")
            if not uri:
                continue
            p = root / uri
            if p.exists():
                paths.append(p)
            else:
                # Some exports nest content under a subfolder; fall back to
                # searching the whole export tree by filename.
                alt = next(root.rglob(Path(uri).name), None)
                if alt:
                    paths.append(alt)

        if not paths:
            continue

        posts.append(Post(key=str(int(ts_raw)), timestamp=ts, caption=caption, media=paths))

    posts.sort(key=lambda p: p.timestamp)
    log(f"[i] Found {len(posts)} post(s) in the export.")
    return posts


